  /// Resolves the localized country name for a given ISO country code and language code.
  /// Normalizes regional variants (e.g. zh_CN -> zh, pt_BR -> pt, ja_JP -> ja).
  static String? getCountryName(String countryCode, String languageCode) {
    final code = countryCode.toUpperCase().trim();
    final lang = _normalizeLanguageCode(languageCode);
    return _countryTranslations[code]?[lang];
  }

  static String _normalizeLanguageCode(String raw) {
    final lower = raw.toLowerCase().trim();
    if (lower.startsWith('zh')) return 'zh';
    final parts = lower.split(RegExp(r'[-_]'));
    return parts.isNotEmpty ? parts.first : 'en';
  }
