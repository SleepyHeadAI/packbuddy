  /// Returns avatars filtered by category
  static List<AnimalAvatar> getByCategory(AnimalCategory category) {
    if (category == AnimalCategory.all) return all;
    return all.where((a) => a.category == category).toList();
  }

  /// Finds an avatar by its id (e.g. 'animal_cat' or 'avatar:animal_cat')
  static AnimalAvatar? findById(String? rawId) {
    if (rawId == null || rawId.isEmpty) return null;
    final cleanId = rawId.startsWith('avatar:') ? rawId.substring(7) : rawId;
    for (final avatar in all) {
      if (avatar.id == cleanId) return avatar;
    }
    return null;
  }

  /// Checks if the photoUrl indicates an animal avatar
  static bool isAnimalAvatar(String? photoUrl) {
    if (photoUrl == null || photoUrl.isEmpty) return false;
    if (photoUrl.startsWith('avatar:')) return true;
    return findById(photoUrl) != null;
  }

  /// Formats avatar ID as a URI string for storage
  static String toUri(String id) {
    final cleanId = id.startsWith('avatar:') ? id.substring(7) : id;
    return 'avatar:$cleanId';
  }
