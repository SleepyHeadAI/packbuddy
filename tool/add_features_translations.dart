    exit(1);
  }

  for (final lang in translations.keys) {
    final file = File('lib/l10n/app_$lang.arb');
    if (!file.existsSync()) {
      print('Warning: File not found: ${file.path}');
      continue;
    }

    final content = file.readAsStringSync();
    final json = jsonDecode(content) as Map<String, dynamic>;

    final langTranslations = translations[lang]!;
    int addedCount = 0;

    for (final entry in langTranslations.entries) {
      if (!json.containsKey(entry.key)) {
        json[entry.key] = entry.value;
        addedCount++;
      }
    }

    if (addedCount > 0) {
      const encoder = JsonEncoder.withIndent('  ');
      file.writeAsStringSync('${encoder.convert(json)}\n');
      print('Added $addedCount keys to app_$lang.arb');
    } else {
      print('No new keys needed for app_$lang.arb');
    }
  }

